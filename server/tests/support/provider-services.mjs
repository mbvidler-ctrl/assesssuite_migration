class TestStripeProviderError extends Error {
  constructor(message, details = {}) {
    super(message);
    this.name = 'TestStripeProviderError';
    Object.assign(this, details);
  }
}

const checkoutSessions = new Map();
const customerEmails = new Map();

export const testStripeProvider = Object.freeze({
  providerId: 'test',
  testOnly: true,
  requiresSignedWebhook: false,
  corroboratesCheckoutSubscription: false,
  enforcesApplicationMetadata: false,
  errorClass: TestStripeProviderError,
  enabled: () => true,
  priceIdForPlan: () => MOCK_CHECKOUT_PRICE_ID,
  trialPeriodDays: () => null,
  approvedPriceIds: () => [MOCK_CHECKOUT_PRICE_ID],
  promotionIdPattern: /^(?:promo_|mock_promo_)[A-Za-z0-9_-]+$/,
  checkoutIdempotencyKeyFor,
  checkoutSessionRequestSha256,
  stripeRequestIdFor: () => null,
  async createCheckoutSession(input) {
    const result = createMockCheckoutSession(input);
    const session = {
      ...result,
      id: result.id.replace(/^mock_/, '').replaceAll('-', ''),
      status: 'open',
      expires_at: Math.floor(Date.now() / 1000) + 1800,
      metadata: {
        userId: input.userId,
        userEmail: input.userEmail,
        priceId: input.priceId,
        appId: input.appId,
        professionId: input.professionId,
        checkoutIntentId: input.checkoutIntentId,
        ...(input.qaSequence ? { qaSequence: input.qaSequence } : {}),
      },
      url: result.url,
    };
    checkoutSessions.set(session.id, session);
    return session;
  },
  async retrieveCheckoutSession(id) {
    const session = checkoutSessions.get(id);
    if (!session) throw new TestStripeProviderError('Checkout Session not found', { status: 404 });
    return session;
  },
  createPortalSession: async (input) => createMockPortalSession(input),
  cancelSubscription: async (id) => cancelMockSubscription(id),
  async findCustomerByEmail(email) {
    const customer = findMockSubscriptionByEmail(email)?.customer || null;
    if (customer?.id) customerEmails.set(customer.id, email);
    return customer;
  },
  async listSubscriptionsForCustomer(customerId) {
    const email = customerEmails.get(customerId);
    const row = email ? findMockSubscriptionByEmail(email) : null;
    return row?.subscription ? [row.subscription] : [];
  },
  async retrieveSubscription(id) {
    for (const session of checkoutSessions.values()) {
      const row = findMockSubscriptionByEmail(session.customer_email);
      if (row?.subscription?.id === id) return row.subscription;
    }
    throw new TestStripeProviderError('Subscription not found', { status: 404 });
  },
  verifyStripeSignatureHeader: () => ({ ok: true }),
  recordSubscription: recordMockSubscription,
  listPromotionCodes: async () => listMockPromotionCodes(),
  createCoupon: async (input) => createMockCoupon(input),
  createPromotionCode: async (input) => createMockPromotionCode(input),
  deactivatePromotionCode: async (id) => deactivateMockPromotionCode(id),
  deleteCoupon: async (id) => deleteMockCoupon(id),
});

export function invokeLlmFallback({ prompt, schema }) {
  if (schema) return instantiateSchema(schema, 'response');
  const keys = extractJsonKeysFromPrompt(prompt);
  if (keys?.length) {
    return JSON.stringify(Object.fromEntries(keys.map((key) => [
      key,
      `Mock generated content for "${key}". Placeholder clinical narrative produced by the local InvokeLLM mock — not real AI output.`,
    ])));
  }
  const topic = typeof prompt === 'string' && prompt.trim()
    ? prompt.trim().slice(0, 80).replace(/\s+/g, ' ')
    : 'the requested topic';
  return (
    `This is placeholder narrative content generated by the local InvokeLLM mock in place of ` +
    `a real language model call. It stands in for a response to a prompt beginning: "${topic}". ` +
    `The mock produces deterministic, non-clinical filler prose of sufficient length to exercise ` +
    `downstream formatting, word-count, and editing logic without contacting any external service.`
  );
}

export function transcriptionFallback({ action, audioUrl, hasTranscript }) {
  if (action === 'transcribe') {
    const label = typeof audioUrl === 'string' && audioUrl
      ? audioUrl.split('/').pop()
      : 'session recording';
    return {
      transcript:
        `[Fallback transcript for ${label}]\n\n` +
        'Clinician: How has your pain been since the last session?\n' +
        'Client: A little better, still stiff in the mornings.\n' +
        'Clinician: Let us run through today\'s exercises and reassess your range of motion.\n\n' +
        '(This is placeholder text produced by an isolated test adapter; no real audio transcription occurred.)',
      simulated: true,
    };
  }
  const notice = '[Simulated SOAP note — placeholder content, not generated from AI analysis of the transcript.] ';
  return {
    success: true,
    simulated: true,
    subjective: notice + (hasTranscript
      ? 'Client reports improved pain levels since last session, with residual morning stiffness.'
      : 'Client reports as discussed during the session.'),
    objective: notice + 'Range of motion and exercise tolerance reassessed during today\'s session.',
    assessment: notice + 'Client demonstrates continued progress consistent with the current treatment plan.',
    plan: notice + 'Continue current exercise programme; reassess at next scheduled session.',
  };
}

