test('R03 resolver semantics over a cartesian environment sweep, one flag per posture', () => {
  const cases = [undefined, '', '0', '1', 'true'];
  const selftestValues = [undefined, '1'];
  const parityValues = [undefined, '1'];
  for (const [name, posture] of [
    ['LLM_REQUIRED', 'strict'],
    ['ALLOW_OPEN_REGISTRATION', 'implied-on'],
    ['OUTBOUND_EMAIL_ENABLED', 'forced-off'],
  ]) {
    for (const value of cases) {
      for (const selftest of selftestValues) {
        for (const parity of parityValues) {
          const environment = { [name]: value, SELFTEST: selftest, PARITY_ASSURANCE_MODE: parity };
          const enabled = capabilityEnabled(name, environment);
          const impliedOnBySelftest = posture === 'implied-on' && selftest === '1';
          if ((value === 'true' || value === '') && !impliedOnBySelftest) {
            assert.equal(enabled, false, `${name}=${JSON.stringify(value)} must never enable the switch itself (posture ${posture})`);
          }
          if (posture === 'forced-off' && (selftest === '1' || parity === '1')) {
            assert.equal(enabled, false, `${name} must be forced off under SELFTEST/PARITY_ASSURANCE_MODE`);
          }
        }
      }
    }
  }
});

