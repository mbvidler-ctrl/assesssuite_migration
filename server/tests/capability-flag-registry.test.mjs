test('R11 parity binding — the registry\'s values.parity drives assertParityAssuranceEnvironment without editing productionBootstrap.mjs', () => {
  const baseEnvironment = { PARITY_ASSURANCE_MODE: '1', ASSESSSUITE_DB_PATH: PARITY_ASSURANCE_DB_PATH, UPLOADS_DIR: PARITY_ASSURANCE_UPLOADS_DIR };
  for (const flag of CAPABILITY_FLAGS) {
    if (flag.values.parity !== null) baseEnvironment[flag.name] = flag.values.parity;
  }
  assert.doesNotThrow(() => assertParityAssuranceEnvironment(baseEnvironment));

  for (const flag of CAPABILITY_FLAGS) {
    if (flag.values.parity === null) continue;
    const mutated = { ...baseEnvironment, [flag.name]: flag.values.parity === '1' ? '0' : '1' };
    assert.throws(() => assertParityAssuranceEnvironment(mutated), new RegExp(`requires ${flag.name}=`));
  }
  for (const extra of ['ASSESSSUITE_DB_PATH', 'UPLOADS_DIR']) {
    const mutated = { ...baseEnvironment, [extra]: 'mutated-value' };
    assert.throws(() => assertParityAssuranceEnvironment(mutated), new RegExp(`requires ${extra}=`));
  }
});

