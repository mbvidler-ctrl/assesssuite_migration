test('R00 characterises pre-refactor InvokeLLM and transcription-reporting behaviour', async () => {
  // (a) The untested-anywhere-else carve-out: GENERAL_CLINICAL_LLM_ENABLED
  // unset, harness default SELFTEST=1 -> the self-test mock path (200).
  const unsetServer = await startTestServer();
  try {
    const admin = await loginEligibleClinician(unsetServer);
    const result = await requestJson(
      unsetServer,
      `/api/apps/${unsetServer.appId}/integration-endpoints/Core/InvokeLLM`,
      { method: 'POST', token: admin, body: { prompt: 'R00 unset+selftest characterisation' } },
    );
    assert.equal(result.status, 200, result.text);
    assert.equal(typeof result.body, 'string');
    assert.match(result.body, /placeholder narrative content generated by the local InvokeLLM mock/i);

    const publicSettings = await requestJson(
      unsetServer,
      `/api/apps/public/prod/public-settings/by-id/${unsetServer.appId}`,
    );
    assert.equal(publicSettings.status, 200, publicSettings.text);
    assert.equal(publicSettings.body?.public_settings?.transcription_enabled, false);
  } finally {
    await unsetServer.stop();
  }

  // (b) Explicit '0' -> 503, exact body. The `code` is P1's machine-readable
  // capability-withdrawal signal (server/capabilities.mjs's
  // CLINICAL_AI_DISABLED_CODE), not the generic 'internal_error' this
  // characterisation originally recorded; the error *message* is unchanged
  // and is the byte-identical string the flag registry documents.
  // server/tests/public-capabilities-contract.test.mjs C02 owns that code.
  const disabledServer = await startTestServer({ GENERAL_CLINICAL_LLM_ENABLED: '0' });
  try {
    const admin = await loginAdmin(disabledServer);
    const result = await requestJson(
      disabledServer,
      `/api/apps/${disabledServer.appId}/integration-endpoints/Core/InvokeLLM`,
      { method: 'POST', token: admin, body: { prompt: 'R00 disabled characterisation' } },
    );
    assert.equal(result.status, 503, result.text);
    assert.deepEqual(result.body, {
      code: 'ai_capability_disabled',
      error: 'General AI generation is disabled on this server.',
    });
  } finally {
    await disabledServer.stop();
  }

  // (c) '1' + LLM_REQUIRED='0' + no key -> 200 mock.
  const enabledServer = await startTestServer({
    GENERAL_CLINICAL_LLM_ENABLED: '1',
    LLM_REQUIRED: '0',
    OPENAI_API_KEY: '',
  });
  try {
    const admin = await loginEligibleClinician(enabledServer);
    const result = await requestJson(
      enabledServer,
      `/api/apps/${enabledServer.appId}/integration-endpoints/Core/InvokeLLM`,
      { method: 'POST', token: admin, body: { prompt: 'R00 enabled characterisation' } },
    );
    assert.equal(result.status, 200, result.text);
    assert.equal(typeof result.body, 'string');
    assert.match(result.body, /placeholder narrative content generated by the local InvokeLLM mock/i);
  } finally {
    await enabledServer.stop();
  }
});

