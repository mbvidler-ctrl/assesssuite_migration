// R05 — the equivalence net. Each entry is a literal copy of the
// pre-refactor expression for that flag, held here (not derived from the
// registry) so this test would have caught Design 1's two selftest-fatal
// substitutions. Green the moment Change 1 lands; its job is to make the
// Change 2 call-site refactor provably safe.
const PRE_REFACTOR_ENABLED = new Map([
  ['ALLOW_OPEN_REGISTRATION', (e) => e.ALLOW_OPEN_REGISTRATION === '1' || e.SELFTEST === '1'],
  ['CORE_V1_SANDBOX_ENABLED', (e) => e.CORE_V1_SANDBOX_ENABLED === '1'],
  ['DOCUMENT_EXTRACTION_ENABLED', (e) => e.DOCUMENT_EXTRACTION_ENABLED === '1'],
  ['DOCUMENT_EXTRACTION_UNDER_13_ENABLED', (e) => e.DOCUMENT_EXTRACTION_UNDER_13_ENABLED === '1'],
  ['GENERAL_CLINICAL_LLM_ENABLED', (e) => e.GENERAL_CLINICAL_LLM_ENABLED === '1'],
  ['LLM_REQUIRED', (e) => e.LLM_REQUIRED === '1'],
  ['OUTBOUND_EMAIL_ENABLED', (e) => !(e.SELFTEST === '1' || e.PARITY_ASSURANCE_MODE === '1') && e.OUTBOUND_EMAIL_ENABLED === '1'],
  ['OUTBOUND_SMS_ENABLED', (e) => !(e.SELFTEST === '1' || e.PARITY_ASSURANCE_MODE === '1') && e.OUTBOUND_SMS_ENABLED === '1'],
  ['PAYMENTS_ENABLED', (e) => !(e.SELFTEST === '1' || e.PARITY_ASSURANCE_MODE === '1') && e.PAYMENTS_ENABLED === '1'],
  ['TRANSCRIPTION_ENABLED', (e) => e.TRANSCRIPTION_ENABLED === '1' || e.SELFTEST === '1'],
  ['UPLOAD_AUDIT_LEGAL_HOLD', (e) => e.UPLOAD_AUDIT_LEGAL_HOLD === '1'],
]);
const PRE_REFACTOR_CONFIGURED = new Map(CAPABILITY_FLAG_NAMES.map((name) => [name, (e) => e[name] === '1']));

test('R05 equivalence net — capabilityEnabled/capabilityConfigured match the literal pre-refactor expressions', () => {
  assert.equal(PRE_REFACTOR_ENABLED.size, 11);
  const cases = [undefined, '', '0', '1', 'true'];
  for (const name of CAPABILITY_FLAG_NAMES) {
    const expectedEnabled = PRE_REFACTOR_ENABLED.get(name);
    const expectedConfigured = PRE_REFACTOR_CONFIGURED.get(name);
    for (const value of cases) {
      for (const selftest of [undefined, '1']) {
        for (const parity of [undefined, '1']) {
          const environment = { [name]: value, SELFTEST: selftest, PARITY_ASSURANCE_MODE: parity };
          assert.equal(
            capabilityEnabled(name, environment),
            expectedEnabled(environment),
            `capabilityEnabled(${name}) drifted from the pre-refactor expression for ${JSON.stringify(environment)}`,
          );
          assert.equal(
            capabilityConfigured(name, environment),
            expectedConfigured(environment),
            `capabilityConfigured(${name}) drifted for ${JSON.stringify(environment)}`,
          );
        }
      }
    }
  }
});

const REGISTERED_NAMES_PATTERN = new RegExp(`^(?:${CAPABILITY_FLAG_NAMES.join('|')})$`);

function walkServerMjsFiles(root) {
  const entries = fs.readdirSync(root, { recursive: true, withFileTypes: true });
  const files = [];
  for (const entry of entries) {
    if (!entry.isFile() || !entry.name.endsWith('.mjs')) continue;
    const dir = entry.parentPath || entry.path || root;
    files.push(path.join(dir, entry.name));
  }
  return files;
}

test('R06 chokepoint scan — zero raw reads of a registered flag outside the registry', () => {
  const serverRoot = path.join(repoRoot, 'server');
  const offenders = [];
  for (const file of walkServerMjsFiles(serverRoot)) {
    const relPath = path.relative(repoRoot, file).split(path.sep).join('/');
    if (relPath.startsWith('server/tests/')) continue;
    if (relPath === 'server/capabilityFlags.mjs') continue;
    if (relPath === 'server/productionBootstrap.mjs') continue; // allowlisted data file, bound by R11
    const text = fs.readFileSync(file, 'utf8');
    for (const hit of scanRawEnvironmentReads(text)) {
      if (REGISTERED_NAMES_PATTERN.test(hit.name)) offenders.push(`${relPath}:${hit.line} (${hit.name})`);
    }
  }
  assert.deepEqual(offenders, []);
});

